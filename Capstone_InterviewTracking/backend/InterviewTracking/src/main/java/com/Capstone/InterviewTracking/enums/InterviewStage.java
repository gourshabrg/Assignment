package com.Capstone.InterviewTracking.enums;

/**
 * Represents the current stage of a candidate in the hiring pipeline.
 */
public enum InterviewStage {

    /** Candidate's profile is being reviewed by HR. */
    PROFILING,

    /** Candidate is ready for the screening call. */
    SCREENING,

    /** Candidate is in the first technical interview. */
    L1,

    /** Candidate is in the second technical interview. */
    L2,

    /** Candidate has reached the final HR round. */
    HR
}
